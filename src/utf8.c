/********************************************************************
 *
 * UTF-8 encoding
 *
 * | bytes         | bytes input
 * | output        |   0   |   1   |   2   |   3   | 
 * |---------------+-------+-------+-------+-------+
 * | 0-7F          | 00-7F |   x   |   x   |   x   | 
 * | 80-7FF        | C0-DF | 80-BF |   x   |   x   |
 * | 800-FFFF      | E0-EF | 80-BF | 80-BF |   x   |
 * | 010000-10FFFF | F0-F7 | 80-BF | 80-BF | 80-BF |
 *
 * So, any value under 0x80 is ascii, 1 byte.
 * char & 0xF8 == 0xF0 then 4 bytes.
 * char & 0xF0 == 0xE0 then 3 bytes;
 * char & 0xE0 == 0xC0 then 2 bytes;
 * Anything else is invalid. Checking subsequent bytes, each must
 * char & 0xC0 == 0x80 or it's an invalid continuation character
 ********************************************************************/

